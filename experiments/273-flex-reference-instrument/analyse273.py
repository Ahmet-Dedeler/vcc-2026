def verdict(name: str, b: dict, plolo: tuple | None) -> str:
    if plolo is None:
        return "—"
    p, lo, hi = plolo
    here_sign = 0 if (b["lo"] <= 0 <= b["hi"]) else (1 if b["point"] > 0 else -1)
    plolo_sign = 0 if (lo is not None and lo <= 0 <= hi) else (1 if p > 0 else -1)
    if plolo_sign == 0 and here_sign == 0:
        return "HOLDS (null both)"
    if plolo_sign != 0 and here_sign == plolo_sign:
        return "HOLDS"
    if plolo_sign != 0 and here_sign == -plolo_sign:
        return "REVERSES"
    if plolo_sign != 0 and here_sign == 0:
        return "BLURS (decisive on PLOLO, interval covers 0 here)" if abs(b["point"]) < abs(p) or np.sign(b["point"]) != np.sign(p) else "BLURS (same sign, interval covers 0)"
    return "BLURS (null on PLOLO, signed here)"


