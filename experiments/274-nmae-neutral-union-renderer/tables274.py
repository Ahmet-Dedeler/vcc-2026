"""274 -- markdown tables from work/price274.json (+ work/mech274-<fold>.json when present) -> work/tables274.md.
    uv run python experiments/274-nmae-neutral-union-renderer/tables274.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
WORK = HERE / "work"
CANCER = ("k562_gwps", "orion_hct116", "orion_hek293t")
d = json.loads((WORK / "price274.json").read_text())
cells = d["cells"]
agg = d["aggregates"]
L: list[str] = []


def P(s=""):
    L.append(s)


def ret(c):
    r = c["conc"]["3"]["retained"]
    return f"{100*r:.0f} %" if abs(c["d_pds_ABC"]) >= 0.0005 and np.isfinite(r) else "—"


def row_screen(n):
    c = cells[n]
    s = c["scenarios"]
    b = c["boot"]["pooled"]
    return (f"| `{n}` | {100*c['rel_cos_agg']:+.2f} | {100*c['rel_macro']:+.2f} | {c['d_pds_ABC']:+.5f} | {c['pds_pos_folds']}/3 | [{b['lo']:+.4f}, {b['hi']:+.4f}] | "
            f"{c['d_pds_A']:+.5f} | {c['d_nmae_wald89']:+.5f} | {c['d_nmae_wald89_3c']:+.5f} | {c['e']:+.2f} | {c['d_precision89']:+.4f} | {c['amp_calibrated_pct']:+.2f} | "
            f"**{s['PESSIMISTIC']['total']:+.5f}** | {s['POINT']['total']:+.5f} | {s['OPTIMISTIC']['total']:+.5f} | {c['cons258']['total']:+.5f} | {ret(c)} | {c['kolf2']['d_pds']:+.5f} |")


HDR = ("| cell | agg % | mac % | Δ`pds` ABC | + | bootstrap 95 % | Δ`pds` A | Δ`nmae` 4f | Δ`nmae` 3c | e | Δprec89 | amp % | PESS | POINT | OPT | C258 | ret3 | `kolf2` Δ`pds` |\n"
       "|---|---:|---:|---:|:-:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
names = list(cells)
groups = [
    ("T0 — R0: the unions at their own magnitudes (258 / 259's rows, reproduced at 0.0e+00)",
     ["stack6 g=0.35", "stack6 g=0.28", "stack6 g=0.2", "stack3 g=0.35", "stack3 g=0.28", "B3 g2=0.35", "B3 g2=0.45", "B4+igvf g2=0.35"]),
    ("T1 — R1 / R2: the six-source union at g = 0.35, every set × mode (`wald89` = the ORACLE pool, a ceiling, not buildable)",
     [n for n in names if n.startswith("stack6 g=0.35 |")]),
    ("T2 — R3: `stack3` (H1 pair + `dld1_lowmoi`) at g = 0.35 and 0.28, and the six-source union at g = 0.28 and 0.20, rendered",
     [n for n in names if any(n.startswith(b) for b in ("stack3 g=0.35 |", "stack3 g=0.28 |", "stack6 g=0.28 |", "stack6 g=0.2 |")) and "PERM" not in n]),
    ("T3 — R4: 259's construction B (the pair kept at 0.28 + `union2`) rendered",
     [n for n in names if (n.startswith("B3 ") or n.startswith("B4")) and "PERM" not in n and "|" in n]),
    ("T4 — controls: the identity check (X_arm := X_ref) and energy-matched random directions (PERM = gene permutation of the union's per-row contribution; SHUF = 218's target derangement) rendered the same way",
     [n for n in names if n.startswith("cd4svd5 IDENT") or "PERM" in n or "SHUF" in n]),
]
P("# 274 — tables (generated by `tables274.py` from `work/price274.json`)")
P()
P("Columns: agg % / mac % = relative `cos_agg` / macro cosine vs `cd4svd5` (mean of per-fold ratios, three cancer folds); Δ`pds` ABC = 246's functional "
  "(a23 render, frames A/B/C mean; + = folds > 0; bootstrap = paired target bootstrap of the three-fold mean, stratified by fold, 20,000 draws, seed 20260906); "
  "Δ`pds` A = six229's frame-A functional; Δ`nmae` = 188's exact identity on the `wald89` pool (4 folds pooled as `six229.py` does / 3 cancer folds); e = ΔM/ΔU; "
  "Δprec89 = top-89 precision (4 folds); amp % = calibrated effect-level delivered amplitude vs `cd4svd5` (production frame; the fold frame for the oracle set); "
  "PESS / POINT / OPT = the three coherent six-member totals (READ-FIRST §3; k_cos 0.94 / 0.96 / 1.00, k_pds 0.7 / 2.48, DE-three 0.0425 / 0.24, identity ×1.5 on a "
  "loss and ×0 on a gain pessimistic); C258 = 258's conservative set (frame A, k_pds 0.7, ×1.5); ret3 = leave-top-3-out `pds` retention (shown where |Δ`pds`| ≥ 0.0005); "
  "`kolf2` apart.")
for title, subset in groups:
    P()
    P(f"## {title}")
    P()
    P(HDR)
    for n in subset:
        P(row_screen(n))

# ---- six members three ways, every cell ------------------------------------------------------
P()
P("## T5 — every cell, six members priced three ways (overall units; `reach`/`fid`/`jac` = the DE-three propagation split by 218's rate card; amp = the amplitude leg inside `mse`, shown apart)")
P()
P("| cell | scenario | `pds` | `mse` | `nmae` | `reach` | `fid` | `jac` | (amp) | TOTAL |")
P("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
for n in names:
    c = cells[n]
    for which in ("PESSIMISTIC", "POINT", "OPTIMISTIC"):
        s = c["scenarios"][which]
        P(f"| `{n}` | {which.lower()} | {s['o_pds']:+.5f} | {s['o_mse']:+.5f} | {s['o_nmae']:+.5f} | {s['o_reach']:+.5f} | {s['o_fid']:+.5f} | {s['o_jac']:+.5f} | {s['o_amp']:+.5f} | **{s['total']:+.5f}** |")

# ---- per-fold pds and the identity ------------------------------------------------------------
P()
P("## T6 — per-fold Δ`pds` (ABC functional) and per-fold bootstrap intervals, the buildable and oracle cells of the main union")
P()
P("| cell | k562_gwps | orion_hct116 | orion_hek293t | pooled | P(≤ 0) | `kolf2` |")
P("|---|---|---|---|---|---:|---:|")
for n in ["stack6 g=0.35"] + [m for m in names if m.startswith("stack6 g=0.35 |")] + ["B3 g2=0.35", "B3 g2=0.35 | all rank", "B3 g2=0.35 | own400 ratio", "B4+igvf g2=0.35", "B4+igvf g2=0.35 | all rank", "B4+igvf g2=0.35 | wald89 ratio"]:
    c = cells[n]
    b = c["boot"]
    per = " | ".join(f"{b['per_fold'][h]['point']:+.4f} [{b['per_fold'][h]['lo']:+.4f}, {b['per_fold'][h]['hi']:+.4f}]" for h in CANCER)
    P(f"| `{n}` | {per} | {b['pooled']['point']:+.5f} [{b['pooled']['lo']:+.4f}, {b['pooled']['hi']:+.4f}] | {b['pooled']['frac_le0']:.3f} | {c['kolf2']['d_pds']:+.4f} |")

# ---- 262 groups ---------------------------------------------------------------------------------
P()
P("## T7 — Δ`pds` by 262's base-cosine group (anti-aligned ≤ 0 / marginal (0, 0.05] / saturated > 0.05; n per fold in brackets), and targets crossing the 0.02 own-cosine knee")
P()
P("| cell | anti-aligned | marginal | saturated | crossing up / down |")
P("|---|---:|---:|---:|---:|")
for n in ["stack6 g=0.35"] + [m for m in names if m.startswith("stack6 g=0.35 |")] + ["stack3 g=0.35", "stack3 g=0.35 | all rank", "stack3 g=0.35 | supp rank", "B3 g2=0.35", "B3 g2=0.35 | all rank", "B3 g2=0.35 | own400 ratio", "B4+igvf g2=0.35", "B4+igvf g2=0.35 | all rank", "B4+igvf g2=0.35 | wald89 ratio", "stack6 g=0.35 PERM20260906 | all rank"]:
    c = cells[n]
    g = c["groups"]
    P(f"| `{n}` | {g['anti']['d_pds']:+.4f} {g['anti']['n']} | {g['marginal']['d_pds']:+.4f} {g['marginal']['n']} | {g['saturated']['d_pds']:+.4f} | {c['cross_up']} / {c['cross_down']} |")

# ---- the mechanism from mech274 -----------------------------------------------------------------
mech = {h: json.loads((WORK / f"mech274-{h}.json").read_text()) for h in CANCER if (WORK / f"mech274-{h}.json").exists()}
if mech:
    P()
    P("## T8 — where the union's transfer-cosine gain sits on the row (`mech274.py`; frame A, a23 render, scored columns; means over the union's carried rows, three cancer folds)")
    P()
    P("The own cosine is Σ_g p_g t_g over unit rows; each set's share is its part of that sum. Δ = the arm minus `cd4svd5` on the same rows.")
    P()
    P("| arm | own cos | Δ own cos | Δ ip on `wald89` | Δ ip on `own89` | Δ ip on `own400` | Δ ip off `own400` | pred energy on `wald89` | on `own400` | L1 on `wald89` / inc | sign acc on `wald89` |")
    P("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    arms = list(mech[CANCER[0]]["arms"])
    tshare = float(np.mean([np.mean(np.array(mech[h]["truth_energy_share_wald89"])[np.array(mech[h]["carried"])]) for h in CANCER]))
    tshare_all = float(np.mean([np.mean(mech[h]["truth_energy_share_wald89"]) for h in CANCER]))
    summary = {}
    for a in arms:
        vals = {k: [] for k in ("own", "dwn", "d89", "d400", "doff", "e89", "e400", "l1", "sg", "d_own")}
        for h in CANCER:
            m = np.array(mech[h]["carried"])
            inc = mech[h]["arms"]["cd4svd5"]
            r = mech[h]["arms"][a]
            f = lambda k, rec: np.array(rec[k])[m]
            vals["own"].append(f("own_cos", r).mean())
            vals["d_own"].append((f("own_cos", r) - f("own_cos", inc)).mean())
            vals["dwn"].append((f("ip_wald89", r) - f("ip_wald89", inc)).mean())
            vals["d89"].append((f("ip_own89", r) - f("ip_own89", inc)).mean())
            vals["d400"].append((f("ip_own400", r) - f("ip_own400", inc)).mean())
            vals["doff"].append(((f("own_cos", r) - f("ip_own400", r)) - (f("own_cos", inc) - f("ip_own400", inc))).mean())
            vals["e89"].append(f("energy_wald89", r).mean())
            vals["e400"].append(f("energy_own400", r).mean())
            vals["l1"].append((f("l1_wald89", r) / f("l1_wald89", inc)).mean())
            vals["sg"].append(f("signacc_wald89", r).mean())
        v = {k: float(np.mean(x)) for k, x in vals.items()}
        summary[a] = v
        P(f"| `{a}` | {v['own']:+.5f} | {v['d_own']:+.5f} | {v['dwn']:+.5f} | {v['d89']:+.5f} | {v['d400']:+.5f} | {v['doff']:+.5f} | {v['e89']:.4f} | {v['e400']:.4f} | {v['l1']:.4f} | {v['sg']:.4f} |")
    P()
    P(f"The truth's `wald89` pool carries {100*tshare:.1f} % of the truth's unit-row energy on the carried rows ({100*tshare_all:.1f} % over all rows).")
    r0 = summary.get("stack6 g=0.35")
    if r0 and r0["d_own"] != 0:
        P(f"Share of the six-source union's own-cosine gain that sits on the 89 `wald89` genes: **{100*r0['dwn']/r0['d_own']:.0f} %**; on the incumbent's own top-89: {100*r0['d89']/r0['d_own']:.0f} %; on the incumbent's own top-400: {100*r0['d400']/r0['d_own']:.0f} %.")
    (WORK / "mech274-summary.json").write_text(json.dumps(dict(summary=summary, truth_share_wald89_carried=tshare, truth_share_wald89_all=tshare_all), indent=1))

(WORK / "tables274.md").write_text("\n".join(L) + "\n")
print(f"wrote {WORK/'tables274.md'} ({len(L)} lines)")
