def slice_out(text: str, names: list[str]) -> str:
    """Top-level `def`/`class`/decorated blocks with the given names, verbatim and in
    source order.  A decorator line immediately above a kept def is kept with it."""
    lines = text.splitlines(keepends=True)
    starts: list[tuple[int, int]] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("def ") or line.startswith("class "):
            name = line.split()[1].split("(")[0].split(":")[0]
            begin = i
            j = i - 1
            while j >= 0 and lines[j].lstrip().startswith("@"):
                begin = j
                j -= 1
            end = i + 1
            while end < len(lines) and (
                lines[end].strip() == ""
                or lines[end].startswith((" ", "\t", ")", "]", "}"))
            ):
                end += 1
            if name in names:
                starts.append((begin, end))
            i = end
        else:
            i += 1
    found = []
    for begin, end in starts:
        chunk = "".join(lines[begin:end]).rstrip("\n")
        found.append(chunk)
    return "\n\n\n".join(found) + "\n"


