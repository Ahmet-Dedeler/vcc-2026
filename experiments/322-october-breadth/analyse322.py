"""322 — tables.  Levels, contributions, and RETENTION in 233's unit.

DEFINITIONS, stated once.

  * A source's CONTRIBUTION on a (panel, fold) is the arm minus the stack without it:
        rel `cos_agg`  =  (cos_agg[arm] - cos_agg[BASE]) / cos_agg[BASE]
        d `pds`        =   pds[arm] - pds[BASE]
    233 §5 uses exactly these two columns for the four October-only sources.

  * RETENTION of a contribution is  contribution(disjoint draw) / contribution(today).
    It is only meaningful when today's contribution is non-zero and of a definite sign; the
    table prints "—" otherwise and never divides two numbers of opposite sign silently.

  * The RESAMPLED UNIT is the PANEL DRAW.  233 built two (`real`, `pess`).  n = 2 bounds every
    interval in this file; three folds are three re-readings of one draw, not three draws.
    Fold spread is reported as a range, never as an interval on the draw.

    uv run python analyse322.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lib322 as L  # noqa: E402

FOLDS = ("k562_gwps", "orion_hct116", "orion_hek293t")
SHORT = {"k562_gwps": "K562", "orion_hct116": "HCT116", "orion_hek293t": "HEK293T"}
PANELS = ("abc", "real", "pess")
PLABEL = {"abc": "abc (today)", "real": "real (draw 1)", "pess": "pess (draw 2)"}
OUT = []


def Pr(s=""):
    OUT.append(s)
    print(s)


def load(name):
    p = L.WORK / name
    return json.loads(p.read_text()) if p.exists() else []


def index(rows, base_arm="BASE"):
    by = {}
    for r in rows:
        by[(r["panel"], r["fold"], r["arm"])] = r
    return by


def contrib(by, panel, fold, arm, base_arm="BASE"):
    a = by.get((panel, fold, arm))
    b = by.get((panel, fold, base_arm))
    if a is None or b is None or "cos_agg" not in a:
        return None
    return dict(rel_cos=(a["cos_agg"] - b["cos_agg"]) / b["cos_agg"],
                d_pds=a["pds"] - b["pds"],
                d_nmae=(a.get("nmae") - b.get("nmae")) if a.get("nmae") is not None
                and b.get("nmae") is not None else None,
                d_fid=(a.get("fid") - b.get("fid")) if a.get("fid") is not None
                and b.get("fid") is not None else None,
                d_reach=(a.get("reach") - b.get("reach")) if a.get("reach") is not None
                and b.get("reach") is not None else None,
                carrying=a.get("carrying_rows"))


def ret(new, old, floor=1e-9):
    """disjoint / today, printed only when today's contribution is not ~0."""
    if old is None or new is None or abs(old) < floor:
        return None
    return new / old


def fmt(x, n=5, pct=False):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "—"
    return f"{100*x:+.2f} %" if pct else f"{x:+.{n}f}"


def main() -> None:
    census = json.loads((L.WORK / "census322.json").read_text())
    br = load("breadth322.json")
    rf = load("refit322.json")          # the re-extracted kolf2, residual form
    bd = load("basedonor322.json") + load("basedonor_refit322.json")
    cn = load("controls322.json")
    # `refit322.json` carries its own BASE rows; they must equal the screen's before the
    # arm rows can share a denominator.
    base_delta = 0.0
    by_tmp = index(br)
    for r in rf:
        if r["arm"] == "BASE":
            o = by_tmp.get((r["panel"], r["fold"], "BASE"))
            if o:
                base_delta = max(base_delta, abs(r["cos_agg"] - o["cos_agg"]),
                                 abs(r["pds"] - o["pds"]))
    assert base_delta == 0.0, f"refit BASE differs from the screen's by {base_delta:.3e}"
    br = br + [r for r in rf if r["arm"] != "BASE"]
    by_br, by_bd, by_cn = index(br), index(bd), index(cn)

    Pr("# 322 — tables (generated by `analyse322.py`; every number is a measured local "
       "PLOLO reading on 233's panels, never a delivered board value)\n")

    # ---------------------------------------------------------------- KA
    Pr("## KA. 233's own rows, reproduced\n")
    KA_LEVELS = {("abc", "k562_gwps"): (0.03698, 0.80719),
                 ("abc", "orion_hct116"): (0.02943, 0.78935),
                 ("abc", "orion_hek293t"): (0.02390, 0.75906),
                 ("real", "k562_gwps"): (0.03906, 0.71394),
                 ("real", "orion_hct116"): (0.02536, 0.68340),
                 ("real", "orion_hek293t"): (0.02067, 0.65316),
                 ("pess", "k562_gwps"): (0.03866, 0.69928),
                 ("pess", "orion_hct116"): (0.02115, 0.65482),
                 ("pess", "orion_hek293t"): (0.01719, 0.65168)}
    Pr("| # | gate | expected (R233 §3.1 / KA-F) | measured | verdict |")
    Pr("|---|---|---|---|---|")
    Pr(f"| KA-1 | 233's coverage census, 15 sources × 3 panels | 25 published rows | "
       f"**{census['ka_f_pass']}/{len(census['ka_f'])} exact** | "
       f"{'**PASS**' if census['ka_f_pass'] == len(census['ka_f']) else 'FAIL'} |")
    n_ok = 0
    worst = 0.0
    for (p, f), (c, d) in KA_LEVELS.items():
        r = by_br.get((p, f, "BASE"))
        if r is None:
            continue
        dc, dp = abs(r["cos_agg"] - c), abs(r["pds"] - d)
        worst = max(worst, dc, dp)
        n_ok += int(dc < 5e-6 and dp < 5e-6)
    Pr(f"| KA-2 | the shipped stack's `cos_agg` / `pds` on 9 (panel, fold) cells | R233 §3.1's "
       f"table to 5 d.p. | **{n_ok}/9 cells**, worst |Δ| **{worst:.1e}** | "
       f"{'**PASS**' if n_ok == 9 else 'FAIL'} |")
    if by_cn:
        agree = []
        for p in PANELS:
            for f in FOLDS:
                a = by_br.get((p, f, "BASE"))
                b = by_cn.get((p, f, "CTRL_BASE"))
                if a and b:
                    agree.append(max(abs(a["cos_agg"] - b["cos_agg"]), abs(a["pds"] - b["pds"])))
        if agree:
            Pr(f"| KA-3 | the controls script's own BASE == the screen's BASE | 0 | "
               f"max |Δ| **{max(agree):.1e}** on {len(agree)} cells | "
               f"{'**PASS**' if max(agree) == 0.0 else 'check'} |")
    if by_bd:
        agree = []
        for p in PANELS:
            for f in FOLDS:
                a = by_br.get((p, f, "BASE"))
                b = by_bd.get((p, f, "BASE_2donor"))
                if a and b:
                    agree.append(max(abs(a["cos_agg"] - b["cos_agg"]), abs(a["pds"] - b["pds"])))
        if agree:
            Pr(f"| KA-4 | the base-donor script's two-donor base == the screen's BASE | 0 | "
               f"max |Δ| **{max(agree):.1e}** on {len(agree)} cells | "
               f"{'**PASS**' if max(agree) == 0.0 else 'check'} |")
    ka5 = load("ka5_322.json")
    if ka5:
        theirs = json.loads((L.ROOT / "experiments/233-october-retention/work/oct233.json")
                            .read_text())
        tk = {(r["panel"], r["fold"], r["arm"]): r for r in theirs}
        n, worst = 0, 0.0
        for r in ka5:
            k = (r["panel"], r["fold"], r["arm"])
            if k in tk:
                worst = max(worst, abs(r["cos_agg"] - tk[k]["cos_agg"]),
                            abs(r["pds"] - tk[k]["pds"]))
                n += 1
        Pr(f"| KA-5 | 233 §5's own Phase-3 ARM rows (`rpe1` on both disjoint draws, doses 0.20 "
           f"and 0.34, plus its derangement) re-run through 322's copy of `oct233.run()` | "
           f"0 | **{n}/{n} rows at {worst:.1e}** | "
           f"{'**PASS**' if worst == 0.0 else 'FAIL'} |")
    Pr()

    # ---------------------------------------------------------------- census
    Pr("## T1. The two senses of \"broad\", and which one predicts October\n")
    Pr("| source | perturbations TOTAL | on today's panel | `real` draw | `pess` draw | "
       "kept, disjoint mean / today |")
    Pr("|---|---:|---:|---:|---:|---:|")
    for r in sorted(census["rows"], key=lambda r: -r["abc"]):
        keep = ((r["real"] + r["pess"]) / 2 / r["abc"]) if r["abc"] else None
        Pr(f"| `{r['source']}` | {r['n_perts']} | {r['abc']} | {r['real']} | {r['pess']} | "
           f"{'—' if keep is None else f'{100*keep:.0f} %'} |")
    Pr()

    # ---------------------------------------------------------------- levels & contributions
    sources = []
    for r in br:
        a = r["arm"]
        if a in ("BASE",) or a.endswith("VACUOUS"):
            continue
        nm = a.split("@")[0]
        if nm.endswith("_shuf"):
            continue
        if nm not in sources:
            sources.append(nm)

    Pr("## T2. Each candidate's CONTRIBUTION on each panel (residual form, dose g = 0.34, "
       "carrying-row sizing)\n")
    Pr("Contribution = arm − the shipped stack, same fold, same operator, same CD4 banks. "
       "`shuf` is the same source whole-row deranged at the same dose (233's null).\n")
    Pr("| source | panel | carrying rows (K562 / HCT116 / HEK293T) | rel `cos_agg` per fold |"
       " mean | `shuf` mean | Δ`pds` per fold | mean | `shuf` mean |")
    Pr("|---|---|---|---|---:|---:|---|---:|---:|")
    table = {}
    for nm in sources:
        for p in PANELS:
            cs, ps, css, pss, carr = [], [], [], [], []
            for f in FOLDS:
                c = contrib(by_br, p, f, f"{nm}@0.34")
                cshuf = contrib(by_br, p, f, f"{nm}_shuf@0.34")
                if c is None:
                    vac = by_br.get((p, f, f"{nm}@VACUOUS"))
                    if vac is not None:
                        cs.append(0.0); ps.append(0.0); carr.append(0)
                    continue
                cs.append(c["rel_cos"]); ps.append(c["d_pds"]); carr.append(c["carrying"])
                if cshuf:
                    css.append(cshuf["rel_cos"]); pss.append(cshuf["d_pds"])
            if not cs:
                continue
            table[(nm, p)] = dict(rel_cos=float(np.mean(cs)), d_pds=float(np.mean(ps)),
                                  rel_cos_folds=cs, d_pds_folds=ps,
                                  shuf_cos=float(np.mean(css)) if css else None,
                                  shuf_pds=float(np.mean(pss)) if pss else None,
                                  carrying=carr,
                                  n_pos_pds=int(sum(x > 0 for x in ps)))
            t = table[(nm, p)]
            sc_s = fmt(t["shuf_cos"], pct=True)
            sp_s = fmt(t["shuf_pds"])
            carr_s = " / ".join(str(x) for x in carr)
            cs_s = " / ".join(f"{100*x:+.2f}" for x in cs)
            ps_s = " / ".join(f"{x:+.5f}" for x in ps)
            Pr(f"| `{nm}` | {p} | {carr_s} | {cs_s} | **{100*t['rel_cos']:+.2f} %** | "
               f"{sc_s} | {ps_s} | **{t['d_pds']:+.5f}** | {sp_s} |")
    Pr()

    # ---------------------------------------------------------------- retention
    Pr("## T3. RETENTION of the contribution — disjoint draw / today (233's unit)\n")
    Pr("| source | rel `cos_agg` today | `real` | `pess` | retention (cos) | "
       "Δ`pds` today | `real` | `pess` | retention (`pds`) |")
    Pr("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for nm in sources:
        a = table.get((nm, "abc"))
        if a is None:
            continue
        r_, p_ = table.get((nm, "real")), table.get((nm, "pess"))
        rc = [ret(x["rel_cos"], a["rel_cos"]) if x else None for x in (r_, p_)]
        rp = [ret(x["d_pds"], a["d_pds"]) if x else None for x in (r_, p_)]
        mrc = None if any(x is None for x in rc) else float(np.mean(rc))
        mrp = None if any(x is None for x in rp) else float(np.mean(rp))
        Pr(f"| `{nm}` | {fmt(a['rel_cos'], pct=True)} | "
           f"{fmt(r_['rel_cos'] if r_ else None, pct=True)} | "
           f"{fmt(p_['rel_cos'] if p_ else None, pct=True)} | "
           f"**{'—' if mrc is None else f'{100*mrc:.0f} %'}** | "
           f"{fmt(a['d_pds'])} | {fmt(r_['d_pds'] if r_ else None)} | "
           f"{fmt(p_['d_pds'] if p_ else None)} | "
           f"**{'—' if mrp is None else f'{100*mrp:.0f} %'}** |")
    Pr()

    # ---------------------------------------------------------------- base donor
    if bd:
        Pr("## T4. `kolf2` as an extra BASE DONOR (264's construction), all three panels\n")
        Pr("| bank | panel | fold | kolf2 rows | amplification (kolf2 / production) | arm | "
           "rows changed vs the two-donor base | max\\|Δ\\| | rel `cos_agg` | Δ`pds` |")
        Pr("|---|---|---|---:|---|---|---:|---:|---:|---:|")
        for suf, lab in (("", "frozen (`data/external/kolf2`, 273 rows)"),
                         ("_refit", "re-extracted for the panel (10,167-row atlas)")):
            for p in PANELS:
                for f in FOLDS:
                    b = by_bd.get((p, f, f"BASE_2donor{suf}"))
                    if b is None:
                        continue
                    pa = b.get("production_amplification") or {}
                    amp = (f"{b['kolf2_amplification']:.0f}× / "
                           f"{'-'.join(f'{v:.1f}' for v in pa.values())}×"
                           if np.isfinite(b.get("kolf2_amplification", float("nan")))
                           else "— (no rows)")
                    for tag in ("equal", "matched"):
                        a = by_bd.get((p, f, f"mean3:{tag}{suf}"))
                        if a is None:
                            continue
                        if "cos_agg" in a:
                            rc = (a["cos_agg"] - b["cos_agg"]) / b["cos_agg"]
                            dp = a["pds"] - b["pds"]
                            rcs, dps = fmt(rc, pct=True), fmt(dp)
                        else:
                            rcs = dps = "**identity**"
                        Pr(f"| {lab} | {p} | {SHORT[f]} | {b['kolf2_carrying_rows']} | {amp} "
                           f"| `mean3:{tag}` | {a.get('rows_changed')} | "
                           f"{a.get('max_abs_diff', 0.0):.3e} | {rcs} | {dps} |")
        Pr()
        Pr("### T4b. The same, averaged over the three folds\n")
        Pr("| bank | panel | `mean3:equal` rel `cos_agg` / Δ`pds` | "
           "`mean3:matched` rel `cos_agg` / Δ`pds` | folds with Δ`pds` > 0 (matched) |")
        Pr("|---|---|---|---|---:|")
        for suf, lab in (("", "frozen"), ("_refit", "re-extracted")):
            for p in PANELS:
                cells = {}
                npos = 0
                for tag in ("equal", "matched"):
                    cs, ps = [], []
                    for f in FOLDS:
                        b = by_bd.get((p, f, f"BASE_2donor{suf}"))
                        a = by_bd.get((p, f, f"mean3:{tag}{suf}"))
                        if not (a and b and "cos_agg" in a):
                            continue
                        cs.append((a["cos_agg"] - b["cos_agg"]) / b["cos_agg"])
                        ps.append(a["pds"] - b["pds"])
                    cells[tag] = ((float(np.mean(cs)), float(np.mean(ps))) if cs else None)
                    if tag == "matched" and ps:
                        npos = sum(x > 0 for x in ps)
                if not any(cells.values()):
                    continue
                Pr(f"| {lab} | {p} | " + " | ".join(
                    "identity (0 rows)" if cells[t] is None
                    else f"{fmt(cells[t][0], pct=True)} / {fmt(cells[t][1])}"
                    for t in ("equal", "matched")) + f" | {npos}/3 |")
        Pr()

    # ---------------------------------------------------------------- controls
    if cn:
        import collections
        arms = sorted({r["arm"] for r in cn if r["arm"] != "CTRL_BASE"})
        grp = collections.defaultdict(lambda: collections.defaultdict(list))
        for p in PANELS:
            for f in FOLDS:
                for a in arms:
                    c = contrib(by_cn, p, f, a, base_arm="CTRL_BASE")
                    if c is None:
                        continue
                    src, rest = a.split("|")[0], a.split("|")[1].split("@")[0]
                    kind = "common" if rest.startswith("common") else "random"
                    k = int("".join(ch for ch in rest.split("_")[0] if ch.isdigit()))
                    grp[p][(src, kind, k)].append(c)

        Pr("## T5a. Control 1 — the COVERAGE LADDER (`dld1_lowmoi`, its own rows cut at "
           "random to k targets, 2-3 seeds x 3 folds, dose 0.34)\n")
        Pr("Does the contribution track how many targets are reached?\n")
        Pr("| k targets | abc rel `cos_agg` | `real` | `pess` | disjoint mean / abc | "
           "abc Δ`pds` | `real` | `pess` |")
        Pr("|---:|---:|---:|---:|---:|---:|---:|---:|")
        ks = sorted({k for p in PANELS for (s, kd, k) in grp[p] if s == "dld1_lowmoi"
                     and kd == "random"})
        lad = {}
        for k in ks:
            cells = {}
            for p in PANELS:
                v = grp[p].get(("dld1_lowmoi", "random", k))
                cells[p] = (float(np.mean([x["rel_cos"] for x in v])),
                            float(np.mean([x["d_pds"] for x in v]))) if v else None
            if cells["abc"] is None:
                continue
            dis = [cells[p][0] for p in ("real", "pess") if cells[p]]
            r = (float(np.mean(dis)) / cells["abc"][0]) if dis and abs(cells["abc"][0]) > 1e-9 else None
            lad[k] = (cells, r)
            Pr(f"| {k} | {fmt(cells['abc'][0], pct=True)} | "
               f"{fmt(cells['real'][0] if cells['real'] else None, pct=True)} | "
               f"{fmt(cells['pess'][0] if cells['pess'] else None, pct=True)} | "
               f"**{'—' if r is None else f'{100*r:.0f} %'}** | "
               f"{fmt(cells['abc'][1])} | "
               f"{fmt(cells['real'][1] if cells['real'] else None)} | "
               f"{fmt(cells['pess'][1] if cells['pess'] else None)} |")
        # the full-coverage row from the main screen, for the top of the ladder
        for p in PANELS:
            t = table.get(("dld1_lowmoi", p))
            if t is None:
                lad = lad
        a, r_, p_ = (table.get(("dld1_lowmoi", x)) for x in PANELS)
        if a:
            dis = [x["rel_cos"] for x in (r_, p_) if x]
            rr = float(np.mean(dis)) / a["rel_cos"] if dis else None
            Pr(f"| all (67 / 67 / 72) | {fmt(a['rel_cos'], pct=True)} | "
               f"{fmt(r_['rel_cos'] if r_ else None, pct=True)} | "
               f"{fmt(p_['rel_cos'] if p_ else None, pct=True)} | "
               f"**{'—' if rr is None else f'{100*rr:.0f} %'}** | {fmt(a['d_pds'])} | "
               f"{fmt(r_['d_pds'] if r_ else None)} | {fmt(p_['d_pds'] if p_ else None)} |")
        Pr()

        Pr("## T5b. Control 2 — COVERAGE HELD FIXED (both sources restricted to the rows "
           "BOTH carry on that panel), with the coverage-matched RANDOM restriction beside it\n")
        Pr("| panel | k | `dld1_lowmoi` common | `igvf_cardiomyocyte` common | "
           "`dld1` random k | `igvf` random k |")
        Pr("|---|---:|---:|---:|---:|---:|")
        for p in PANELS:
            keys = [k for (s, kd, k) in grp[p] if kd == "common"]
            if not keys:
                continue
            k = keys[0]
            def g(s, kd, kk):
                v = grp[p].get((s, kd, kk))
                if not v:
                    return None
                return (float(np.mean([x["rel_cos"] for x in v])),
                        float(np.mean([x["d_pds"] for x in v])))
            rand_k = sorted({kk for (s, kd, kk) in grp[p] if kd == "random"
                             and abs(kk - k) <= 1})
            rk = rand_k[0] if rand_k else None
            cells = [g("dld1_lowmoi", "common", k), g("igvf_cardiomyocyte", "common", k),
                     g("dld1_lowmoi", "random", rk) if rk else None,
                     g("igvf_cardiomyocyte", "random", rk) if rk else None]
            Pr(f"| {p} | {k} | " + " | ".join(
                "—" if c is None else f"{fmt(c[0], pct=True)} / {fmt(c[1])}"
                for c in cells) + " |")
        Pr("\n(each cell is `rel cos_agg / Δpds`, mean over the three folds and the seeds)\n")

    (L.WORK / "tables322.md").write_text("\n".join(OUT) + "\n")
    json.dump({f"{k[0]}|{k[1]}": v for k, v in table.items()},
              open(L.WORK / "contrib322.json", "w"), indent=2)
    print(f"\n-> {L.WORK/'tables322.md'}")


if __name__ == "__main__":
    main()
