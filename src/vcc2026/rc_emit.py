import dataclasses

from scipy.stats import false_discovery_control, norm

CALL_SET_OFFSET = 1.0e6
JITTER_SCALE = 1.0e-12


@dataclasses.dataclass(frozen=True)
class CallSet:
    """202: a PRESCRIBED call set, replacing the incumbent's own (experiment 192 section 5.3).

    `n_head` genes by descending `|H|`, then `n_cpm` more by descending control CPM among
    the genes the head did not already take -- so the delivered set is exactly
    `n_head + n_cpm` genes, which is 192's own construction
    (`head = topk(|H|, M); rest = topk(where(head, -inf, cpm), K - M); call = head | rest`).
    Both rankings run over the SCORER's DE universe only (`control.keep`, mean per-cell CPM
    > 5 on that context's own control cells); a gene outside it can never be called, and
    `control.ref_lin` -- the per-gene mean of per-cell CPM over those same control cells --
    IS the CPM the ranking uses.  Ties in either key are broken toward the lower gene index
    by `np.argsort(..., kind="stable")`, which is deterministic and rebuild-stable.

    `z_cap` is the mechanism.  BH's rejection COUNT is a function of the p-value MULTISET,
    and `rc_hybrid` re-assigns the incumbent's multiset unchanged -- so permuting it can
    move which genes are called only if the set has the incumbent's size.  To deliver a
    SMALLER set the multiset itself has to move, and it moves in exactly one place: every
    gene outside the prescribed set has its target `|z|` scaled by one common factor so the
    largest of them lands on `z_cap`.  At `z_cap = 1.90` the smallest complement p-value is
    `2 * sf(1.90) = 0.0574 > alpha = 0.05 >= alpha * i / m` for every position `i <= m`, so
    no complement gene can be rejected at any position, and BH's count is capped at the
    prescribed size.  One common factor keeps the map strictly monotone, so `|H|`'s order
    inside the complement -- the second half of `rc_hybrid`'s delivery law -- is preserved
    exactly.  The prescribed genes keep the top `n_head + n_cpm` values of the incumbent's
    own multiset, untouched.
    """

    n_head: int
    n_cpm: int
    z_cap: float

    @property
    def size(self) -> int:
        return int(self.n_head) + int(self.n_cpm)


@dataclasses.dataclass(frozen=True)
class RcControlBlock:
    """One context's real control cells, in the space the scorer's DE test reads.

    `keep` is the SCORER's gate -- mean per-cell CPM > 5 over the control cells -- and not
    the builder's `--min-cpm`.  A gene outside it can never be called, so its histogram is
    free and 185 uses it as the slack that welds the per-cell totals.
    """

    keep: np.ndarray          # bool, full gene axis: the scorer's 5-CPM DE universe
    cs: np.ndarray            # (G, m) float64, sorted log1p(CPM) rows of the controls
    tie: np.ndarray           # (G,) float64, scanpy tie sums of each control row
    ref_lin: np.ndarray       # (G,) float64, mean per-cell CPM (the lfc denominator)
    n_controls: int
    min_cpm: float


def control_block_from_counts(matrix, *, min_cpm: float = 5.0, chunk: int = 2000):
    """Build `RcControlBlock` from a context's control count matrix (CSR or dense).

    Streamed in row chunks: the dense (18,400 x 18,533) float64 form is 2.7 GB and is never
    materialised.  Two passes, because the gate needs the per-gene mean before the kept
    rows can be laid out.
    """
    n_cells = int(matrix.shape[0])
    n_genes = int(matrix.shape[1])

    def dense_rows(lo, hi):
        block = matrix[lo:hi]
        block = block.toarray() if hasattr(block, "toarray") else np.asarray(block)
        return np.asarray(block, dtype=np.float64)

    cpm = np.zeros(n_genes, dtype=np.float64)
    for lo in range(0, n_cells, chunk):
        block = dense_rows(lo, min(lo + chunk, n_cells))
        sums = block.sum(1)
        sums[sums == 0] = 1.0
        cpm += (block * (1e6 / sums[:, None])).sum(0)
    cpm /= n_cells
    keep = cpm > float(min_cpm)
    n_keep = int(keep.sum())
    cs = np.empty((n_keep, n_cells), dtype=np.float64)
    for lo in range(0, n_cells, chunk):
        hi = min(lo + chunk, n_cells)
        block = dense_rows(lo, hi)
        sums = block.sum(1)
        sums[sums == 0] = 1.0
        cs[:, lo:hi] = np.log1p(block[:, keep] * (1e6 / sums[:, None])).T
    cs.sort(axis=1)
    cs = np.ascontiguousarray(cs)
    return RcControlBlock(
        keep=keep,
        cs=cs,
        tie=ctrl_tiesums(cs),
        ref_lin=np.ascontiguousarray(cpm[keep]),
        n_controls=n_cells,
        min_cpm=float(min_cpm),
    )


def de_from_block(block, control):
    """The scorer's per-gene z / p / BH q / lfc for one emitted (n, G_full) count block."""
    sums = block.sum(1).astype(np.float64)
    sums[sums == 0] = 1.0
    normed = np.log1p(block[:, control.keep] * (1e6 / sums[:, None]))
    z = wilcoxon_z(control.cs, control.tie, np.ascontiguousarray(normed.T))
    p = 2 * norm.sf(np.abs(z))
    q = false_discovery_control(p, method="bh")
    lfc = np.log2((np.expm1(normed).mean(0) + 1e-9) / (control.ref_lin + 1e-9))
    return z, p, q, lfc


def to_csr(block):
    """`emit_counts`'s return contract: (values float32, columns int32, indptr int64)."""
    nonzero = block > 0
    n = block.shape[0]
    indptr = np.zeros(n + 1, dtype=np.int64)
    np.cumsum(nonzero.sum(1), out=indptr[1:])
    rows, cols = np.nonzero(nonzero)
    order = np.lexsort((cols, rows))
    return (
        block[rows[order], cols[order]].astype(np.float32),
        cols[order].astype(np.int32),
        indptr,
    )


def rc_hybrid_block(
    profile,
    lib_sizes,
    dispersion,
    rng,
    *,
    spread,
    overdispersion,
    control,
    key,
    jitter_seed,
    call_set_first: bool = True,
    call_set: "CallSet | None" = None,
    pass2_rng=None,
    max_counts: int = 1_000_000,
    emit_counts=None,
    order_key=None,
):
    """One rank-controlled block: the two-pass emitter of 185 section 7.

    `order_key` (2026-09-11, arm 319o): an OPTIONAL non-negative array over the full gene axis
    that replaces `|key|` as the ORDER inside the call-set block and inside its complement.
    Membership of the prescribed set (`CallSet`'s `|H|` head) and the delivered SIGNS still
    come from `key`, so the call SET and every sign are unchanged and only the p-value
    ORDER moves. `None` (the default) is the shipped behaviour, bit for bit.

    `call_set_first` selects between the two re-keys 185 measured, and it is the ONLY
    difference between them:

      True   (`rc_hybrid`, 185 section 3.4)  the incumbent's own BH call set goes in front
             as one block -- it is a p-threshold set, so BH on the same |z| multiset
             reproduces it exactly -- and `|H|` orders inside it and inside its complement.
      False  (`rc_hist_a`, 185 section 3a)   `|H|` orders the WHOLE gene axis, so the call
             set is re-drawn as the top `n_pred` genes by `|H|` rather than kept.

    `call_set` (202, experiment 192 section 5.3) is the one variable on top of that: when it
    is given, the block in front is the PRESCRIBED set of `CallSet` rather than the
    incumbent's own, and the complement's target `|z|` is scaled below `z_cap` so BH
    delivers it.  `call_set_first` must be True with it -- a prescribed set and a whole-axis
    re-key are two different arms.  Everything else, including the order inside the block
    and inside its complement, is unchanged.

    Everything else is shared: a15's per-gene totals, the `T = S // n` weld, a15's own
    per-perturbation |z| multiset, the `abs` sign policy, the sub-gate tail law, greedy
    placement with sub-gate repair.

    `key` is `|H|` with its sign -- the incumbent's own gated predicted effect on the full
    gene axis.  `emit_counts` is injected so the caller supplies the SHIPPED quasi law
    rather than this module owning a second copy of it.

    `pass2_rng` defaults to `rng`, i.e. the sub-gate emission and the placement continue
    the same stream pass 1 drew from -- which is what the production writer wants, since it
    drives all 900 blocks off one generator.  185's `realize185.py` re-seeded instead (its
    incumbent arm and its rc arm each opened `default_rng(90000 + i)`), so the known-answer
    reproduction passes two fresh generators here.  Nothing but the draws differs, and
    185 section 3e measured the twin spread of this family at 7e-5.

    Returns `(block, diagnostics)` with `block` an (n, G_full) int64 count matrix whose
    per-gene totals equal the quasi law's exactly and whose per-cell totals are welded to
    `T = S // n`, the `S mod n` remainder cells at `T + 1`.
    """
    if emit_counts is None:                       # pragma: no cover - always injected
        from vcc2026.donor_transfer import emit_counts as emit_counts  # noqa: PLC0415

    if pass2_rng is None:
        pass2_rng = rng
    if call_set is not None and not call_set_first:
        raise ValueError("a prescribed call set needs call_set_first=True")
    n = int(len(lib_sizes))
    n_genes = int(np.asarray(profile).size)
    keep = control.keep
    if keep.size != n_genes:
        raise ValueError("control block gate and profile disagree on the gene axis")
    gidx = np.flatnonzero(keep)
    n_keep = int(gidx.size)
    spread_vector = np.asarray(spread, dtype=np.float64)
    if spread_vector.ndim == 0:
        spread_vector = np.full(n_genes, float(spread_vector))
    if spread_vector.size != n_genes:
        raise ValueError("spread must be a scalar or one value per gene")

    # ---- pass 1: the incumbent's own block, through the shipped quasi law --------------
    values, columns, pointers = emit_counts(
        profile, lib_sizes, dispersion, rng, max_counts=max_counts,
        mode="quasi", spread=spread_vector, overdispersion=overdispersion,
    )
    incumbent = np.zeros((n, n_genes), dtype=np.int64)
    for row in range(n):
        lo, hi = int(pointers[row]), int(pointers[row + 1])
        incumbent[row, columns[lo:hi]] = values[lo:hi].astype(np.int64)
    totals = incumbent.sum(0)
    z1, _p1, q1, _lfc1 = de_from_block(incumbent, control)
    called = q1 < 0.05
    del incumbent

    # ---- the welded per-cell totals ----------------------------------------------------
    grand = int(totals.sum())
    per_cell = grand // n
    cell_totals = np.full(n, per_cell, dtype=np.int64)
    cell_totals[: grand % n] += 1

    # ---- the assignment: a15's |z| multiset, re-keyed by |H| ---------------------------
    # `call_set_first` (the hybrid, 185 section 3.4): the call set goes in front as one
    # block (it is a p-threshold set, so BH on the same |z| multiset reproduces it exactly)
    # and `|H|` orders inside it and inside its complement -- the ORDER that maximises
    # `reach` and the SET that maximises `jac` are different objects, and this keeps both.
    # Otherwise (185 section 3a's whole-axis re-key): `|H|` alone orders the gene axis and
    # the call set moves with it.
    key_gated = np.asarray(key, dtype=np.float64)[keep]
    key_abs = np.abs(key_gated)
    if not np.all(np.isfinite(key_abs)):
        raise ValueError("the ordering key carries non-finite entries")
    if float(key_abs.max(initial=0.0)) >= CALL_SET_OFFSET:
        raise ValueError("the ordering key is too large for the call-set block offset")
    jitter = np.random.default_rng(jitter_seed).random(n_keep) * JITTER_SCALE
    # 202: the prescribed set replaces the incumbent's own as the block that goes in front.
    # It is selected on the UNJITTERED keys -- the jitter exists to break `|H|`'s ties in the
    # ORDER, and letting it decide membership would make the set depend on `jitter_seed`.
    called_pass1 = called
    if call_set is not None:
        if call_set.size > n_keep:
            raise ValueError("the prescribed call set is larger than the DE universe")
        head = np.zeros(n_keep, dtype=bool)
        head[np.argsort(-key_abs, kind="stable")[: int(call_set.n_head)]] = True
        cpm_rank = np.where(head, -np.inf, np.asarray(control.ref_lin, dtype=np.float64))
        called = head.copy()
        called[np.argsort(-cpm_rank, kind="stable")[: int(call_set.n_cpm)]] = True
        if int(called.sum()) != call_set.size:
            raise AssertionError("the prescribed call set did not come out at its size")
    block_bonus = (
        np.where(called, CALL_SET_OFFSET, 0.0) if call_set_first
        else np.zeros(n_keep, dtype=np.float64)
    )
    if order_key is None:
        order_abs = key_abs
    else:
        order_abs = np.asarray(order_key, dtype=np.float64)[keep]
        if not np.all(np.isfinite(order_abs)) or float(order_abs.min(initial=0.0)) < 0.0:
            raise ValueError("the order key must be finite and non-negative")
        if float(order_abs.max(initial=0.0)) >= CALL_SET_OFFSET:
            raise ValueError("the order key is too large for the call-set block offset")
    ranked = np.argsort(-(order_abs + jitter + block_bonus), kind="stable")
    position = np.empty(n_keep, dtype=np.int64)
    position[ranked] = np.arange(n_keep)
    z_target = np.sort(np.abs(z1))[::-1][position]
    if call_set is not None:
        # The complement, by construction the positions at or after the block's size.  One
        # common factor -> strictly monotone -> `|H|`'s order inside it is untouched.
        complement = position >= call_set.size
        z_worst = float(z_target[complement].max(initial=0.0))
        if z_worst > call_set.z_cap:
            z_target = z_target.copy()
            z_target[complement] *= call_set.z_cap / z_worst
        if float(z_target[complement].max(initial=0.0)) > call_set.z_cap + 1e-9:
            raise AssertionError("the complement was not targeted below the cap")
    signs = np.sign(key_gated)
    signs[signs == 0] = 1.0
    designed = EME(control.cs, control.tie, per_cell, n).design(
        totals[keep], signs * z_target, mode="abs", T=per_cell
    )

    # ---- the sub-gate block on the incumbent's own tail law, then place and repair ------
    sub_profile = np.where(keep, 0.0, np.asarray(profile, dtype=np.float64))
    values, columns, pointers = emit_counts(
        sub_profile, lib_sizes, dispersion, pass2_rng, max_counts=max_counts,
        mode="quasi", spread=spread_vector, overdispersion=overdispersion,
    )
    sub_block = np.zeros((n, n_genes), dtype=np.int64)
    for row in range(n):
        lo, hi = int(pointers[row]), int(pointers[row + 1])
        sub_block[row, columns[lo:hi]] = values[lo:hi].astype(np.int64)
    if sub_block[:, keep].any():
        raise AssertionError("the sub-gate block leaked into the DE universe")
    block, diagnostics = EME(control.cs, control.tie, per_cell, n).place(
        designed, gidx, sub_block, cell_totals, pass2_rng
    )

    delivered = block.sum(0)
    if not np.array_equal(delivered, totals):
        raise AssertionError("rc_hybrid moved a per-gene panel total")
    if not np.array_equal(block.sum(1), cell_totals):
        raise AssertionError("rc_hybrid did not weld the per-cell totals")
    if block.min() < 0:
        raise AssertionError("rc_hybrid emitted a negative count")
    realised, _p2, q2, _lfc2 = de_from_block(block, control)
    if call_set is not None:
        # The realisation, measured on the block that was actually emitted, and recorded
        # per block.  The only thing asserted here is the MECHANISM -- that every gene
        # outside the prescribed set was actually TARGETED below the cap -- because that is
        # a property of this code and nothing else.  How many of them BH then rejects is a
        # property of the INPUT and must not stop a build:
        #
        #   * the reachable |z| of a gene has a FLOOR (`EME.envelope`'s `z_floor`) set by
        #     its own delivered panel total against the control distribution.  A gene whose
        #     total is far enough from the control cannot be made to look like it at ANY
        #     allocation over 400 cells, so it clears BH however it is targeted.  On
        #     h1-test that is a median of ~15 genes per perturbation, but the distribution
        #     has a tail: a perturbation with a large delivered effect carries hundreds.
        #   * so the delivered call set is `prescribed UNION unsuppressible`, and its size
        #     is a floor the profile sets, not a number the call set can choose.
        #
        # That floor is the arm's real exposure and it is reported rather than enforced.
        delivered_call = q2 < 0.05
        n_delivered = int(delivered_call.sum())
        diagnostics.update(
            call_set_prescribed=int(call_set.size),
            call_set_delivered=n_delivered,
            call_set_jaccard=float(
                (delivered_call & called).sum() / max((delivered_call | called).sum(), 1)
            ),
            call_set_unsuppressible=int((delivered_call & ~called).sum()),
            call_set_missed=int((called & ~delivered_call).sum()),
            call_set_z_target_max=float(np.abs(z_target[complement]).max(initial=0.0)),
            call_set_z_scale=float(
                min(1.0, call_set.z_cap / z_worst) if z_worst > 0 else 1.0
            ),
        )
    diagnostics.update(
        call_set_first=float(bool(call_set_first)),
        n_pred_pass1=int(called_pass1.sum()),
        n_genes_de_universe=n_keep,
        per_cell_total=int(per_cell),
        z_realised_vs_designed_max=float(np.abs(realised - designed["z"]).max()),
        clip_frac=float(np.mean(np.abs(np.abs(designed["z"]) - z_target) > 0.5)),
        sign_flip_frac=float(
            np.mean((np.sign(designed["z"]) != signs) & (z_target > 0.5))
        ),
        sub_gate_spread_max=float(spread_vector[~keep].max(initial=0.0)),
        sub_gate_counts_per_cell=float(sub_block.sum(1).mean()),
    )
    return block, diagnostics
